import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from '@babel/parser';
import generateModule from '@babel/generator';
const generate = generateModule.default || generateModule;
const source = readFileSync('src/main.jsx', 'utf8');
const ast = parse(source, { sourceType: 'module', plugins: ['jsx'] });
writeFileSync('review/main.formatted.jsx', generate(ast, { comments: true }, source).code);
const stats = { useState: (source.match(/useState\(/g) || []).length, useRef: (source.match(/useRef\(/g) || []).length, useEffect: (source.match(/useEffect\(/g) || []).length, jsxBytes: Buffer.byteLength(source), cssLines: readFileSync('src/style.css', 'utf8').split('\n').length, cssBytes: Buffer.byteLength(readFileSync('src/style.css')) };
writeFileSync('review/code-stats.json', JSON.stringify(stats, null, 2));
console.log(JSON.stringify(stats));
