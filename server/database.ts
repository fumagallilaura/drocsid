function safeInteger(value: unknown): number {
  if (typeof value !== 'string' || !/^\d+$/.test(value) || !Number.isSafeInteger(Number(value))) throw new ProtocolError('PERSISTENCE_FAILED');
  return Number(value);
}

function readRoom(row: Row): Room {
  const event = parseServerEvent(JSON.stringify({ v: PROTOCOL_VERSION, type: 'room-created', requestId: 'storage', room: { id: row.id, name: row.name, description: row.description } }));
  if (event.type !== 'room-created') throw new ProtocolError('PERSISTENCE_FAILED');
  return event.room;
}

function readMessage(row: Row): Message {
  const event = parseServerEvent(JSON.stringify({ v: PROTOCOL_VERSION, type: 'message-accepted', requestId: 'storage', message: {
    id: row.id, room: row.room, author: row.author, text: row.text,
    created: safeInteger(row.created), sequence: safeInteger(row.sequence), authorId: row.authorId, operationId: row.operationId,
  } }));
  if (event.type !== 'message-accepted') throw new ProtocolError('PERSISTENCE_FAILED');
  return event.message;
}

function persistenceFailure(error: unknown): ProtocolError {
  // Never carry a driver error, SQL, parameters or connection URL into diagnostics.
  return error instanceof ProtocolError ? error : new ProtocolError('PERSISTENCE_FAILED', 'Não foi possível concluir a operação no banco.');
}

const messageColumns = 'id,room,author,text,created,sequence,author_id AS "authorId",operation_id AS "operationId"';

export class Database {
  private pool: pg.Pool;
  private applicationName = `drocsid-server/${randomUUID()}`;
  private leases = new Set<PoolClient>();
  private closing = false;
  private closePromise?: Promise<void>;

  constructor(private readonly config: PoolConfig) {
    const report = () => { if (!this.closing) console.warn(JSON.stringify({ phase: 'database', code: 'PERSISTENCE_FAILED' })); };
    this.pool = new pg.Pool({ ...config, application_name: this.applicationName, onConnect: client => { client.on('error', report); } });
    this.pool.on('error', report);
  }

  private async withClient<T>(work: (client: PoolClient) => Promise<T>): Promise<T> {
    if (this.closing) throw new ProtocolError('SHUTTING_DOWN');
    let client: PoolClient | undefined;
    try {
      client = await this.pool.connect();
      if (this.closing) { client.release(true); client = undefined; throw new ProtocolError('SHUTTING_DOWN'); }
      this.leases.add(client);
      return await work(client);
    } catch (error) { throw persistenceFailure(error); }
    finally { if (client && this.leases.delete(client)) client.release(); }
  }

  async query(sql: string, values: readonly unknown[] = []): Promise<Row[]> {
    return this.withClient(async client => (await client.query<Row>(sql, [...values])).rows);
  }

  transaction<T>(work: (client: PoolClient) => Promise<T>): Promise<T> {
    return this.withClient(async client => {
      await client.query('BEGIN');
      try { const result = await work(client); await client.query('COMMIT'); return result; }
      catch (error) { try { await client.query('ROLLBACK'); } catch {} throw error; }
    });
  }

  async migrate(): Promise<void> {
    await this.transaction(async client => {
      await client.query('SELECT pg_advisory_xact_lock($1)', [41973921]);
      await client.query(`CREATE SCHEMA IF NOT EXISTS drocsid;
        CREATE TABLE IF NOT EXISTS drocsid.schema_migrations (version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());`);
      const applied = (await client.query<Row>('SELECT version,checksum FROM drocsid.schema_migrations ORDER BY version')).rows;
      if (applied.some((row, index) => row.version !== migrations[index]?.version || row.checksum !== createHash('sha256').update(migrations[index].sql).digest('hex'))) throw new ProtocolError('INCOMPATIBLE_DATABASE');
      for (const migration of migrations.slice(applied.length)) {
        await client.query(migration.sql);
        await client.query('INSERT INTO drocsid.schema_migrations(version,checksum) VALUES ($1,$2)', [migration.version, createHash('sha256').update(migration.sql).digest('hex')]);
      }
    });
  }

  async rooms(): Promise<Room[]> {
    return (await this.query('SELECT id,name,description FROM drocsid.rooms ORDER BY position')).map(readRoom);
  }

  async room(id: string): Promise<Room | undefined> {
    const rows = await this.query('SELECT id,name,description FROM drocsid.rooms WHERE id=$1', [id]);
    return rows[0] ? readRoom(rows[0]) : undefined;
  }

  async createRoom(input: Room): Promise<Room> {
    const room = readRoom(input);
    const rows = await this.query('INSERT INTO drocsid.rooms(id,name,description) VALUES ($1,$2,$3) ON CONFLICT(id) DO NOTHING RETURNING id,name,description', [room.id, room.name, room.description]);
    if (!rows.length) throw new ProtocolError('OPERATION_CONFLICT');
    return readRoom(rows[0]);
  }

  async history(room: string): Promise<Message[]> {
    return (await this.query(`SELECT * FROM (SELECT ${messageColumns} FROM drocsid.messages WHERE room=$1 ORDER BY sequence DESC LIMIT 200) history ORDER BY sequence`, [room])).map(readMessage);
  }

  async saveMessage(input: MessageInput): Promise<Message> {
    return (await this.commitMessage(input)).message;
  }

  async receipt(operationId: string, ownerId: string | null, room: string, text: string): Promise<Message | undefined> {
    const rows = await this.query(`SELECT ${messageColumns},receipt_owner FROM drocsid.messages WHERE operation_id=$1`, [operationId]);
    if (!rows[0]) return;
    if (rows[0].receipt_owner !== ownerId || rows[0].room !== room || rows[0].text !== text) throw new ProtocolError('OPERATION_CONFLICT');
    return readMessage(rows[0]);
  }

  async commitMessage(input: MessageInput): Promise<{ message: Message; inserted: boolean }> {
    if (!input.operationId || (input.ownerId !== null && input.ownerId !== input.authorId)) throw new ProtocolError('INVALID_INPUT');
    readMessage({ ...input, created: String(input.created), sequence: '1' });
    return this.transaction(async client => {
      const rows = (await client.query<Row>(`INSERT INTO drocsid.messages(id,room,author,text,created,author_id,operation_id,receipt_owner)
        VALUES ($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT(operation_id) DO NOTHING RETURNING ${messageColumns}`,
      [input.id, input.room, input.author, input.text, input.created, input.authorId, input.operationId, input.ownerId])).rows;
      if (rows.length) return { message: readMessage(rows[0]), inserted: true };
      const existing = (await client.query<Row>(`SELECT ${messageColumns},receipt_owner FROM drocsid.messages WHERE operation_id=$1`, [input.operationId])).rows[0];
      if (!existing || existing.receipt_owner !== input.ownerId || existing.room !== input.room || existing.text !== input.text) throw new ProtocolError('OPERATION_CONFLICT');
      return { message: readMessage(existing), inserted: false };
    });
  }

  close(): Promise<void> {
    if (this.closePromise) return this.closePromise;
    this.closing = true;
    this.closePromise = (async () => {
      let failed = false;
      if (this.leases.size) {
        // Closing a socket does not interrupt a running PostgreSQL statement.
        // This one bounded control connection targets only this pool's unique tag.
        const control = new pg.Client({ ...this.config, application_name: 'drocsid-shutdown' });
        control.on('error', () => { failed = true; });
        try {
          await control.connect();
          const result = await control.query<{ terminated: boolean }>(`SELECT pg_terminate_backend(pid,500) AS terminated FROM pg_stat_activity
            WHERE application_name=$1 AND datname=current_database() AND usename=current_user AND pid<>pg_backend_pid()`, [this.applicationName]);
          if (result.rows.some(row => !row.terminated)) failed = true;
        } catch { failed = true; }
        finally { await control.end().catch(() => { failed = true; }); }
      }
      for (const client of this.leases) { this.leases.delete(client); client.release(true); }
      await this.pool.end();
      if (failed) throw new ProtocolError('SHUTDOWN_FAILED');
    })();
    return this.closePromise;
  }
}

export async function createDatabase(env: Environment = process.env): Promise<Database> {
  const database = new Database(databaseConfig(env));
  try { await database.migrate(); return database; }
  catch (error) { await database.close().catch(() => {}); throw persistenceFailure(error); }
}
