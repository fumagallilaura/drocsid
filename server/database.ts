import pg from 'pg';
import type { PoolClient, PoolConfig } from 'pg';
import { createHash, randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { PROTOCOL_VERSION, ProtocolError, parseServerEvent } from '../shared/protocol.js';
import type { Message, Room } from '../shared/protocol.js';

type Environment = { DATABASE_URL?: string; PG_CA_FILE?: string };
type Row = Record<string, unknown>;
export type MessageInput = Omit<Message, 'sequence' | 'operationId'> & { operationId: string; ownerId: string | null };

export function databaseConfig(env: Environment): PoolConfig {
  try {
    if (!env.DATABASE_URL) throw new Error();
    const url = new URL(env.DATABASE_URL);
    if (!['postgres:', 'postgresql:'].includes(url.protocol) || !url.username || !url.password || url.pathname.length < 2 || url.hash) throw new Error();
    const loopback = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    for (const [key, value] of url.searchParams) if (key !== 'sslmode' || value !== 'verify-full') throw new Error();
    const tls = !loopback || !!env.PG_CA_FILE || url.searchParams.has('sslmode');
    // pg reparses TLS query options. Remove them so they cannot replace this policy.
    url.search = '';
    return {
      connectionString: url.href, max: 8, connectionTimeoutMillis: 3000,
      statement_timeout: 3000, lock_timeout: 1000, idle_in_transaction_session_timeout: 3000,
      application_name: 'drocsid-server',
      ssl: tls ? { rejectUnauthorized: true, ...(env.PG_CA_FILE ? { ca: readFileSync(env.PG_CA_FILE, 'utf8') } : {}) } : false,
    };
  } catch { throw new ProtocolError('INVALID_INPUT', 'Configuração PostgreSQL inválida. Configure DATABASE_URL e certificados no servidor.'); }
}

